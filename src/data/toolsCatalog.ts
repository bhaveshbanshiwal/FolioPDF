export const TOOL_BY_ID: Record<ToolId, ToolDefinition> = TOOLS_CATALOG.reduce(
  (acc, tool) => {
    acc[tool.id] = tool;
    return acc;
  },
  {} as Record<ToolId, ToolDefinition>,
);

export function isValidToolId(value: string): value is ToolId {
  return Object.prototype.hasOwnProperty.call(TOOL_BY_ID, value);
}
